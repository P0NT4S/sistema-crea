class Carousel extends UIBase {
    constructor(core, parent, items = [], config = {}) {
        super(core, parent, 'pts-carousel', 'div');
        this.items = items; // Array de UIBase ou HTMLElement
        this.config = config;

        this.render();
    }

    render() {
        this.el.innerHTML = `
            <div class="pts-carousel-fade-left" style="opacity: 0;"></div>
            <div class="pts-carousel-inner"></div>
            <div class="pts-carousel-fade-right"></div>
        `;

        const inner = this.el.querySelector('.pts-carousel-inner');
        const fadeLeft = this.el.querySelector('.pts-carousel-fade-left');
        const fadeRight = this.el.querySelector('.pts-carousel-fade-right');

        this.items.forEach(item => {
            const node = item instanceof UIBase ? item.getNode() : item;
            inner.appendChild(node);
        });

        // Lógica de scroll lateral via Mouse Wheel
        inner.addEventListener('wheel', (e) => {
            if (e.deltaY !== 0) {
                e.preventDefault();
                inner.scrollBy({ left: e.deltaY, behavior: 'auto' }); // Scroll instantâneo e preciso
            }
        });

        // Lógica de fade nas bordas conforme o scroll
        inner.onscroll = () => {
            const scrollLeft = inner.scrollLeft;
            const maxScroll = inner.scrollWidth - inner.clientWidth;

            fadeLeft.style.opacity = scrollLeft > 10 ? '1' : '0';
            fadeRight.style.opacity = scrollLeft < maxScroll - 10 ? '1' : '0';
        };

        // Trigger inicial do scroll para o fade right aparecer se houver overflow
        setTimeout(() => inner.dispatchEvent(new Event('scroll')), 100);
    }

    scrollTo(index) {
        const inner = this.el.querySelector('.pts-carousel-inner');
        const target = inner.children[index];
        if (target) {
            inner.scrollTo({ left: target.offsetLeft - 20, behavior: 'smooth' });
        }
    }
}

class Tabs extends UIBase {
    constructor(core, parent, items = [], isCarousel = false) {
        const customClass = isCarousel ? 'pts-tabs-carousel' : '';
        super(core, parent, `pts-tabs-container-wrapper ${customClass}`, 'div');
        this.items = items;
        this.isCarousel = isCarousel;
        this.render();
    }

    render() {
        this.el.innerHTML = '';

        const tabsContainer = document.createElement('div');
        tabsContainer.className = 'pts-tabs-container';

        this.items.forEach((item, index) => {
            const tab = document.createElement('div');
            if (!this.isCarousel) tab.style.flex = "1";
            tab.style.textAlign = "center";
            tab.className = `pts-tab ${item.active ? 'active' : ''}`;
            tab.innerHTML = `<span class="pts-tab-label">${item.label}</span>`;

            tab.onclick = () => {
                const allTabs = this.el.querySelectorAll('.pts-tab');
                allTabs.forEach(c => c.classList.remove('active'));
                tab.classList.add('active');
                if (item.onClick) item.onClick();
            };

            tabsContainer.appendChild(tab);
        });

        if (this.isCarousel) {
            const carousel = new Carousel(this.core, this.el, [tabsContainer]);
            carousel.mount();
        } else {
            this.el.appendChild(tabsContainer);
        }
    }
}

